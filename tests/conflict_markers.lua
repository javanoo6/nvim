-- Scan real tracked files, including committed markers and Markdown examples.
local repo = vim.fn.fnamemodify(debug.getinfo(1, "S").source:sub(2), ":p:h:h")
vim.opt.runtimepath:prepend(repo)
local fixture = vim.fn.tempname()
vim.fn.mkdir(fixture .. "/ci", "p")
local function git(...)
  local result = vim.system(vim.list_extend({ "git", "-C", fixture }, { ... }), { text = true }):wait()
  assert(result.code == 0, result.stderr)
end
local function equal(actual, expected)
  assert(vim.deep_equal(actual, expected), "Expected " .. vim.inspect(expected) .. ", got " .. vim.inspect(actual))
end
local function run()
  git("init", "--quiet")
  local conflict = { "#!/bin/sh", "<<<<<<< HEAD", "ours", "=======", "theirs", ">>>>>>> main" }
  vim.fn.writefile(conflict, fixture .. "/ci/utils.sh")
  vim.fn.writefile({ "```", unpack(conflict) }, fixture .. "/example.md")
  vim.fn.writefile({ "~~~", unpack(conflict) }, fixture .. "/example.markdown")
  vim.fn.writefile({ "# Plain heading", "ordinary text" }, fixture .. "/clean.txt")
  git("add", ".")
  git("-c", "user.name=Fixture", "-c", "user.email=fixture@example.invalid", "commit", "--quiet", "-m", "fixture")
  vim.fn.writefile(conflict, fixture .. "/untracked.sh")
  vim.cmd.cd(fixture)
  vim.cmd.edit(fixture .. "/ci/utils.sh")
  local markers = require("util.conflict_markers")
  markers.setup()
  vim.cmd.GitConflictMarkers()
  local qf = vim.fn.getqflist({ title = 1, items = 1 })
  equal(qf.title, "Committed conflict markers")
  equal(#qf.items, 3)
  for index, line in ipairs({ 2, 4, 6 }) do
    equal(qf.items[index].lnum, line)
    equal(qf.items[index].text, conflict[line])
    equal(vim.api.nvim_buf_get_name(qf.items[index].bufnr), fixture .. "/ci/utils.sh")
  end
  equal(vim.api.nvim_win_get_cursor(0)[1], 2)
  equal(vim.bo.buftype, "")
  equal(vim.t.conflict_marker_merge, true)
  equal(#vim.api.nvim_tabpage_list_wins(0), 3)
  local source = vim.api.nvim_get_current_buf()
  local sides = {}
  for _, win in ipairs(vim.api.nvim_tabpage_list_wins(0)) do
    equal(vim.wo[win].diff, true)
    local buffer = vim.api.nvim_win_get_buf(win)
    if buffer ~= source then
      equal(vim.bo[buffer].modifiable, false)
      sides[#sides + 1] = table.concat(vim.api.nvim_buf_get_lines(buffer, 0, -1, false), "\n")
    end
  end
  table.sort(sides)
  equal(sides, { "#!/bin/sh\nours", "#!/bin/sh\ntheirs" })
  markers.choose("ours")
  equal(vim.api.nvim_buf_get_lines(source, 0, -1, false), { "#!/bin/sh", "ours" })
  markers.close_merge()
  equal(vim.api.nvim_get_current_buf(), source)
  equal(vim.bo.modified, true)
  equal(vim.wo.diff, false)
  equal(vim.fn.readfile(fixture .. "/ci/utils.sh"), conflict)
  vim.cmd.cclose()
  vim.cmd("GitConflictMarkers!")
  equal(vim.bo.buftype, "quickfix")
  print("Conflict markers: tracked markers, fenced examples, untracked files, and jump/list modes passed")
end
local ok, err = xpcall(run, debug.traceback)
vim.cmd.cd(repo)
vim.fn.delete(fixture, "rf")
assert(ok, err)
